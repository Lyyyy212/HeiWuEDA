import { createHash } from "node:crypto";
import { existsSync } from "node:fs";
import { mkdir, mkdtemp, readFile, readdir, rm, writeFile } from "node:fs/promises";
import { createRequire } from "node:module";
import { tmpdir } from "node:os";
import path from "node:path";
import { fileURLToPath } from "node:url";

import { build as esbuild } from "esbuild";
import { build as viteBuild } from "vite";

import { CANVAS_BRAND_NAME } from "../shared/branding.mjs";

const require = createRequire(import.meta.url);
const ROOT_DIR = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const GENERATED_DIR = path.join(ROOT_DIR, "mcp", "generated");
const CHECK_ONLY = process.argv.includes("--check");
const GENERATED_HEADER = "Generated by scripts/build-release-artifacts.mjs. Do not edit by hand.";

const artifactNames = {
  mcpApps: "mcp-apps-global-script.mjs",
  mcpBundle: "hardware-learning-mcp.mjs",
  widget: "hardware-learning-widget.html",
  manifest: "release-manifest.json",
};

const temporaryRoot = await mkdtemp(path.join(tmpdir(), "jlc-hardware-learning-release-"));

try {
  const widgetHtml = normalizeGeneratedText(
    await buildWidgetArtifact(path.join(temporaryRoot, "widget-build")),
  );
  const mcpAppsModule = normalizeGeneratedText(await buildMcpAppsGlobalModule());
  const temporaryMcpAppsModule = path.join(temporaryRoot, artifactNames.mcpApps);
  await writeFile(temporaryMcpAppsModule, mcpAppsModule);

  const temporaryMcpBundle = path.join(temporaryRoot, artifactNames.mcpBundle);
  await esbuild({
    entryPoints: [path.join(ROOT_DIR, "mcp", "server.mjs")],
    outfile: temporaryMcpBundle,
    bundle: true,
    platform: "node",
    format: "esm",
    target: "node20",
    charset: "utf8",
    minify: true,
    legalComments: "eof",
    treeShaking: true,
    banner: {
      js: `// ${GENERATED_HEADER}`,
    },
    plugins: [generatedMcpAppsAlias(temporaryMcpAppsModule)],
    logLevel: "warning",
  });

  const mcpBundle = Buffer.from(
    normalizeGeneratedText(await readFile(temporaryMcpBundle, "utf8")),
  );
  await writeFile(temporaryMcpBundle, mcpBundle);
  if (mcpBundle.includes("npm install")) {
    throw new Error("The generated MCP bundle unexpectedly contains a runtime npm install path.");
  }

  const packageJson = JSON.parse(await readFile(path.join(ROOT_DIR, "package.json"), "utf8"));
  const artifacts = new Map([
    [artifactNames.mcpApps, Buffer.from(mcpAppsModule)],
    [artifactNames.mcpBundle, mcpBundle],
    [artifactNames.widget, Buffer.from(widgetHtml)],
  ]);
  const releaseManifest = `${JSON.stringify({
    version: packageJson.version,
    generatedBy: "scripts/build-release-artifacts.mjs",
    artifacts: Object.fromEntries(
      [...artifacts].map(([name, contents]) => [name, sha256(contents)]),
    ),
  }, null, 2)}\n`;
  artifacts.set(artifactNames.manifest, Buffer.from(releaseManifest));

  if (CHECK_ONLY) {
    await checkArtifacts(artifacts);
  } else {
    await writeArtifacts(artifacts);
  }
} finally {
  await rm(temporaryRoot, { recursive: true, force: true });
}

// Vite plugins may retain development-only handles after a programmatic build.
// Release artifact generation is a one-shot command, so exit after cleanup.
process.exit(0);

async function buildWidgetArtifact(outDir) {
  await viteBuild({
    root: ROOT_DIR,
    logLevel: "warning",
    plugins: [normalizeBuildSourceTextPlugin()],
    build: {
      outDir,
      emptyOutDir: true,
    },
  });

  let html = await inlineViteBuild(outDir);
  html = `<!-- ${GENERATED_HEADER} -->\n${html}`;
  if (!html.includes(CANVAS_BRAND_NAME)) {
    throw new Error("The generated JLC Hardware Learning widget does not include the expected app shell.");
  }
  if (!html.includes("jlc-hardware-learning-canvas-v1")) {
    throw new Error("The generated JLC Hardware Learning widget does not contain the dedicated hardware-learning canvas.");
  }
  if (/tl-watermark|Made with tldraw|production license/i.test(html)) {
    throw new Error("The dedicated hardware-learning widget unexpectedly contains the tldraw watermark runtime.");
  }
  return html;
}

async function buildMcpAppsGlobalModule() {
  const sourcePath = require.resolve("@modelcontextprotocol/ext-apps/app-with-deps");
  const source = await readFile(sourcePath, "utf8");
  const exportStart = source.lastIndexOf("export{");
  if (exportStart === -1) {
    throw new Error("Could not find the ext-apps browser export block.");
  }

  const exportBlock = source.slice(exportStart).match(/^export\{([^}]+)\};?\s*$/s);
  if (!exportBlock) {
    throw new Error("Could not parse the ext-apps browser export block.");
  }

  const exportMap = parseExportMap(exportBlock[1]);
  const requiredExports = [
    "App",
    "applyDocumentTheme",
    "applyHostFonts",
    "applyHostStyleVariables",
  ];
  for (const name of requiredExports) {
    if (!exportMap.has(name)) throw new Error(`Missing ext-apps browser export: ${name}`);
  }

  const globalScript = [
    source.slice(0, exportStart),
    ";globalThis.__JLC_HARDWARE_LEARNING_MCP_APPS__={",
    requiredExports.map((name) => `${JSON.stringify(name)}:${exportMap.get(name)}`).join(","),
    "};",
  ].join("");

  return [
    `// ${GENERATED_HEADER}`,
    `export const MCP_APPS_GLOBAL_SCRIPT = ${JSON.stringify(globalScript)};`,
    "",
  ].join("\n");
}

function generatedMcpAppsAlias(generatedModulePath) {
  return {
    name: "jlc-hardware-learning-generated-mcp-apps",
    setup(build) {
      build.onResolve(
        { filter: /mcp-apps-global-script\.mjs$/ },
        () => ({ path: generatedModulePath }),
      );
    },
  };
}

function parseExportMap(body) {
  const exportMap = new Map();
  for (const rawEntry of body.split(",")) {
    const entry = rawEntry.trim();
    if (!entry) continue;
    const parts = entry.split(/\s+as\s+/);
    const local = parts[0]?.trim();
    const exported = (parts[1] || parts[0])?.trim();
    if (local && exported) exportMap.set(exported, local);
  }
  return exportMap;
}

async function inlineViteBuild(outDir) {
  let html = await readFile(path.join(outDir, "index.html"), "utf8");
  const inlineScripts = [];
  const consumedAssets = new Set();

  html = html.replace(
    /<link\s+rel="modulepreload"[^>]+href="([^"]+)"[^>]*>\s*/g,
    "",
  );

  html = await replaceAsync(
    html,
    /<link\s+rel="stylesheet"[^>]+href="([^"]+)"[^>]*>/g,
    async (_match, href) => {
      const css = await readBuildAsset(outDir, href, consumedAssets);
      return `<style>\n${escapeInlineStyle(css)}\n</style>`;
    },
  );

  html = await replaceAsync(
    html,
    /<script\s+type="module"[^>]+src="([^"]+)"[^>]*><\/script>/g,
    async (_match, src) => {
      const js = await readBuildAsset(outDir, src, consumedAssets);
      inlineScripts.push(`<script>\n(() => {\n${escapeInlineScript(js)}\n})();\n</script>`);
      return "";
    },
  );

  if (/\b(?:src|href)\s*=\s*"[^"]*\/assets\//i.test(html)) {
    throw new Error("The JLC Hardware Learning widget still references external build assets.");
  }

  const assetsDir = path.join(outDir, "assets");
  if (existsSync(assetsDir)) {
    const leftovers = (await readdir(assetsDir)).filter(
      (name) => !consumedAssets.has(`assets/${name}`),
    );
    if (leftovers.length > 0) {
      throw new Error(
        `The JLC Hardware Learning widget build emitted non-inlined assets: ${leftovers.join(", ")}`,
      );
    }
  }

  if (inlineScripts.length > 0) {
    const scripts = inlineScripts.join("\n");
    html = html.includes("</body>")
      ? html.replace("</body>", () => `${scripts}\n</body>`)
      : `${html}\n${scripts}`;
  }

  assertCspCompatibleStaticHtml(html);
  return html;
}

async function readBuildAsset(outDir, assetPath, consumedAssets) {
  const normalized = assetPath.replace(/^\//, "");
  consumedAssets.add(normalized);
  return readFile(path.join(outDir, normalized), "utf8");
}

async function replaceAsync(input, pattern, replacer) {
  const matches = Array.from(input.matchAll(pattern));
  if (matches.length === 0) return input;

  let cursor = 0;
  const output = [];
  for (const match of matches) {
    output.push(input.slice(cursor, match.index));
    output.push(await replacer(...match));
    cursor = match.index + match[0].length;
  }
  output.push(input.slice(cursor));
  return output.join("");
}

function assertCspCompatibleStaticHtml(html) {
  const shellMarkup = html
    .replace(/<script\b[\s\S]*?<\/script>/gi, "")
    .replace(/<style\b[\s\S]*?<\/style>/gi, "");

  const forbiddenShellPatterns = [
    [/<script\b[^>]+\bsrc\s*=/i, "external script tag"],
    [/<script\b[^>]*\btype\s*=\s*["']module["']/i, "module script tag"],
    [/<link\b[^>]+\bhref\s*=/i, "external link tag"],
    [/<iframe\b/i, "iframe tag"],
    [/<(?:object|embed|base)\b/i, "embedded/base tag"],
  ];
  for (const [pattern, label] of forbiddenShellPatterns) {
    if (pattern.test(shellMarkup)) {
      throw new Error(`The JLC Hardware Learning widget is not CSP-compatible: found ${label}.`);
    }
  }

  for (const value of resourceAttributeValues(shellMarkup)) {
    if (isExternalResourceValue(value)) {
      throw new Error(
        `The JLC Hardware Learning widget is not CSP-compatible: found external resource ${value}.`,
      );
    }
  }

  if (/\bfetch\s*\(/i.test(html) && !html.includes("__JLC_HARDWARE_LEARNING_WIDGET_FETCH_GUARD__")) {
    throw new Error(
      "The JLC Hardware Learning widget is not CSP-compatible: found fetch() without the fetch guard.",
    );
  }
}

function resourceAttributeValues(markup) {
  return Array.from(
    markup.matchAll(/\b(?:src|href)\s*=\s*(["'])(.*?)\1/gi),
    (match) => match[2].trim(),
  );
}

function isExternalResourceValue(value) {
  if (!value) return false;
  if (/^(?:#|data:|blob:|about:blank\b)/i.test(value)) return false;
  return /^(?:[a-z][a-z0-9+.-]*:|\/\/|\/|\.{1,2}\/)/i.test(value);
}

function escapeInlineScript(source) {
  return source.replaceAll("</script", "<\\/script").replaceAll("</SCRIPT", "<\\/SCRIPT");
}

function escapeInlineStyle(source) {
  return source.replaceAll("</style", "<\\/style").replaceAll("</STYLE", "<\\/STYLE");
}

function sha256(contents) {
  return createHash("sha256").update(contents).digest("hex");
}

function normalizeBuildSourceTextPlugin() {
  return {
    name: "jlc-hardware-learning-normalize-build-source-text",
    enforce: "pre",
    transform(source, id) {
      const cleanId = id.split("?", 1)[0];
      if (!path.isAbsolute(cleanId)) return null;
      const relative = path.relative(ROOT_DIR, cleanId);
      if (
        !relative
        || relative.startsWith(`..${path.sep}`)
        || path.isAbsolute(relative)
        || relative.split(path.sep).includes("node_modules")
      ) {
        return null;
      }
      const normalized = String(source).replace(/\r\n?/gu, "\n");
      return normalized === source ? null : { code: normalized, map: null };
    },
  };
}

function normalizeGeneratedText(value) {
  return String(value).replace(/\r\n?/gu, "\n").replace(/[ \t]+$/gmu, "");
}

async function writeArtifacts(artifacts) {
  await mkdir(GENERATED_DIR, { recursive: true });
  for (const [name, contents] of artifacts) {
    await writeFile(path.join(GENERATED_DIR, name), contents);
  }
  console.log(`Built ${artifacts.size} JLC Hardware Learning release artifacts in ${GENERATED_DIR}.`);
}

async function checkArtifacts(expectedArtifacts) {
  const stale = [];
  for (const [name, expected] of expectedArtifacts) {
    try {
      const actual = await readFile(path.join(GENERATED_DIR, name));
      if (!actual.equals(expected)) stale.push(name);
    } catch (error) {
      if (error?.code === "ENOENT") {
        stale.push(name);
      } else {
        throw error;
      }
    }
  }

  if (stale.length > 0) {
    throw new Error(
      `JLC Hardware Learning release artifacts are missing or stale: ${stale.join(", ")}. Run npm run build:artifacts.`,
    );
  }
  console.log("OK: JLC Hardware Learning release artifacts match the current source.");
}
